"""Rasterizes the interface fonts into core/libcompanion/src/font_data.{h,cpp} (4 bpp, anti-aliased once, here).
Generated and committed; rerun only to change sizes or charsets. Needs Pillow and fontTools.

Order matters: it is the order of cc::FontSize in include/companion/canvas.h, checked by a static_assert.
Design 1a: Unbounded Medium for numbers, Onest for text (assets/fonts, SIL OFL 1.1). Nothing smaller than 22 px.
Unbounded sizes for numbers carry only digits and signs, to keep flash small. Glyphs a font lacks
(card suits, and dots in Onest) are skipped here and drawn with shapes by the interface."""
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS_DIR = ROOT / "assets/fonts"
UNB = FONTS_DIR / "Unbounded-Medium.ttf"
ONEST_R, ONEST_M, ONEST_SB = (FONTS_DIR / f"Onest-{w}.ttf" for w in ("Regular", "Medium", "SemiBold"))

TEXT = "".join(chr(c) for c in range(32, 127)) + "".join(chr(c) for c in range(0x410, 0x450)) + "ЁёІі№°—–…«»•·↑↓←→−●○"
DIGITS = "0123456789 :,.+-−–°%KM"

# name in cc::FontSize, file, pixel size, characters
FONTS = [
    ("NumXXL", UNB, 120, DIGITS), ("NumXL", UNB, 104, DIGITS), ("Num96", UNB, 96, DIGITS), ("Num92", UNB, 92, DIGITS),
    ("Num84", UNB, 84, DIGITS), ("NumL", UNB, 64, DIGITS), ("NumL56", UNB, 56, DIGITS), ("NumM", UNB, 48, DIGITS),
    ("NumM40", UNB, 40, DIGITS), ("NumS", UNB, 36, DIGITS), ("NumS30", UNB, 30, DIGITS),
    ("MenuSel", UNB, 42, TEXT), ("Unb34", UNB, 34, TEXT), ("Unb28", UNB, 28, TEXT),
    ("Title", ONEST_M, 30, TEXT), ("Txt28", ONEST_M, 28, TEXT), ("Body", ONEST_M, 26, TEXT), ("Cap", ONEST_M, 24, TEXT),
    ("Min", ONEST_R, 22, TEXT), ("Btn", ONEST_SB, 22, TEXT),
]


def glyph(font, ch):
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    adv = round(font.getlength(ch))
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return adv, 0, 0, 0, 0, b""
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    px = img.tobytes()
    data = bytearray()
    for r in range(h):
        row = px[r * w: (r + 1) * w]
        for i in range(0, w, 2):
            hi = row[i] >> 4
            lo = row[i + 1] >> 4 if i + 1 < w else 0
            data.append((hi << 4) | lo)
    return adv, w, h, x0, y0, bytes(data)


def main():
    out = ["// Generated by tools/gen_font.py. Do not edit.", '#include "font_data.h"', "namespace cc {"]
    infos = []
    total = 0
    for name, path, size, chars in FONTS:
        font = ImageFont.truetype(str(path), size)
        have = TTFont(str(path)).getBestCmap()
        ascent, descent = font.getmetrics()
        rows, bitmap = [], bytearray()
        for cp in sorted(set(map(ord, chars))):
            if cp not in have:
                continue
            adv, w, h, xo, yo, data = glyph(font, chr(cp))
            assert w < 65536 and h < 65536 and -32768 <= xo < 32768 and adv < 65536, (name, chr(cp))
            rows.append(f"{{{cp},{len(bitmap)},{w},{h},{xo},{yo + ascent},{adv}}}")
            bitmap += data
        out.append(f"static const uint8_t bmp{name}[] = {{" + ",".join(map(str, bitmap)) + "};")
        out.append(f"static const Glyph gl{name}[] = {{" + ",".join(rows) + "};")
        infos.append(f"{{gl{name},{len(rows)},bmp{name},{ascent + descent}}}")
        total += len(bitmap)
        print(f"{name:7} {Path(path).stem:20} {size:4}px  glyphs {len(rows):3}  bytes {len(bitmap)}")
    out.append(f"const FontInfo kFonts[kFontCount] = {{" + ",".join(infos) + "};")
    out.append("}  // namespace cc")
    src = ROOT / "core/libcompanion/src"
    (src / "font_data.cpp").write_text("\n".join(out) + "\n", encoding="utf-8")
    (src / "font_data.h").write_text(
        "// Generated by tools/gen_font.py. Do not edit.\n#pragma once\n#include <stdint.h>\nnamespace cc {\n"
        "struct Glyph { uint32_t cp; uint32_t offset; uint16_t w, h; int16_t xoff; int16_t yoff; uint16_t adv; };\n"
        "struct FontInfo { const Glyph* glyphs; int count; const uint8_t* bitmap; int lineH; };\n"
        f"constexpr int kFontCount = {len(FONTS)};\n"
        "extern const FontInfo kFonts[kFontCount];\n}  // namespace cc\n", encoding="utf-8")
    print("total bitmap bytes", total)


if __name__ == "__main__":
    main()
