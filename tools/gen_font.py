"""Rasterizes DejaVu Sans into core/libcompanion/src/font_data.{h,cpp} (4 bpp, ASCII + Cyrillic).
Generated once and committed; rerun only to change sizes or charset. Needs matplotlib (font) and Pillow."""
import os
from pathlib import Path

import matplotlib
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = os.path.join(matplotlib.get_data_path(), "fonts", "ttf", "DejaVuSans.ttf")
TEXT = "".join(chr(c) for c in range(32, 127)) + "".join(chr(c) for c in range(0x410, 0x450)) + "ЁёІі№°—–…«»•·↑↓←→"
FONTS = [("S", 19, TEXT), ("M", 25, TEXT), ("L", 40, TEXT)]


def glyph(font, ch):
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    adv = round(font.getlength(ch))
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return adv, 0, 0, 0, 0, b""
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    px = img.tobytes()
    data = bytearray()
    for r in range(h):
        row = px[r * w: (r + 1) * w]
        for i in range(0, w, 2):
            hi = row[i] >> 4
            lo = row[i + 1] >> 4 if i + 1 < w else 0
            data.append((hi << 4) | lo)
    return adv, w, h, x0, y0, bytes(data)


def main():
    out = ["// Generated by tools/gen_font.py from DejaVu Sans. Do not edit.", '#include "font_data.h"', "namespace cc {"]
    infos = []
    for name, size, chars in FONTS:
        font = ImageFont.truetype(TTF, size)
        ascent, descent = font.getmetrics()
        rows, bitmap = [], bytearray()
        for cp in sorted(set(map(ord, chars))):
            adv, w, h, xo, yo, data = glyph(font, chr(cp))
            rows.append(f"{{{cp},{len(bitmap)},{w},{h},{xo},{yo + ascent},{adv}}}")
            bitmap += data
        out.append(f"static const uint8_t bmp{name}[] = {{" + ",".join(map(str, bitmap)) + "};")
        out.append(f"static const Glyph gl{name}[] = {{" + ",".join(rows) + "};")
        infos.append(f"{{gl{name},{len(rows)},bmp{name},{ascent + descent}}}")
        print(name, "glyphs", len(rows), "bytes", len(bitmap))
    out.append("const FontInfo kFonts[3] = {" + ",".join(infos) + "};")
    out.append("}  // namespace cc")
    src = ROOT / "core/libcompanion/src"
    (src / "font_data.cpp").write_text("\n".join(out) + "\n", encoding="utf-8")
    (src / "font_data.h").write_text(
        "// Generated by tools/gen_font.py. Do not edit.\n#pragma once\n#include <stdint.h>\nnamespace cc {\n"
        "struct Glyph { uint32_t cp; uint32_t offset; uint8_t w, h; int8_t xoff; int8_t yoff; uint8_t adv; };\n"
        "struct FontInfo { const Glyph* glyphs; int count; const uint8_t* bitmap; int lineH; };\n"
        "extern const FontInfo kFonts[3];\n}  // namespace cc\n", encoding="utf-8")


if __name__ == "__main__":
    main()
