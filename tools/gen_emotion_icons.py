"""Renders every emotion's eyes through the real core into monochrome icons for the Android app, so the app shows
exactly the face the device will make. Brightness becomes alpha: the app tints them like any other icon.
Usage: python tools/gen_emotion_icons.py"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from core.companion import Companion, emotion_names, rgb565_to_rgb888  # noqa: E402

RES = ROOT / "android/app/src/main/res/drawable-nodpi"
KOTLIN = ROOT / "android/app/src/main/java/com/companion/app/EmotionIcons.kt"
WIDTH = 192  # px: crisp up to about 64 dp on the densest screens


def faces():
    c = Companion(seed=7)  # same timing as tools/render_sheet.py: no blink caught mid-way
    c.handle_command({"type": "setting", "name": "sleep_after", "value": 7200})
    c.run(3000)
    for e in emotion_names():
        c.handle_command({"type": "action", "value": "wake"})
        c.run(1500)
        c.handle_command({"type": "emotion", "value": e, "hold_ms": 8000})
        c.run(1200 if e == "yawning" else 2600)
        yield e, Image.fromarray(rgb565_to_rgb888(c.render())).convert("L")
    c.close()


def main():
    shots = list(faces())
    # One crop for all, the union of every face: the eyes keep their height, so sleepy stays low and joy stays high.
    boxes = [im.point(lambda v: 255 if v > 60 else 0).getbbox() for _, im in shots]
    box = (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))
    height = round(WIDTH * (box[3] - box[1]) / (box[2] - box[0]))
    RES.mkdir(parents=True, exist_ok=True)
    for name, im in shots:
        alpha = im.crop(box).resize((WIDTH, height), Image.LANCZOS)
        icon = Image.merge("LA", (Image.new("L", alpha.size, 255), alpha))
        icon.save(RES / f"emo_{name}.png", optimize=True)
    entries = ",\n".join(f'    "{n}" to R.drawable.emo_{n}' for n, _ in shots)
    KOTLIN.write_text("package com.companion.app\n\n// Generated by tools/gen_emotion_icons.py from the core's own faces. Do not edit.\n"
                      f"val EMOTION_ICONS = mapOf(\n{entries},\n)\n", encoding="utf-8")
    assert len(shots) == 50 and all(b is not None for b in boxes), "every emotion must draw visible eyes"
    print(f"{len(shots)} icons {WIDTH}x{height} -> {RES}")


if __name__ == "__main__":
    main()
